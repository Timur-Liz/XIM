function detectKey(topic: string): string {
  const t = topic.toLowerCase();
  if (t.includes("кислот")) return "acids";
  if (t.includes("основан") || t.includes("щёлоч") || t.includes("щелоч")) return "bases";
  if (t.includes("сол")) return "salts";
  if (t.includes("оксид")) return "oxides";
  if (t.includes("кислород")) return "oxygen";
  if (t.includes("водород")) return "hydrogen";
  if (t.includes("вод") || t.includes("раствор")) return "water";
  if (t.includes("периодич") || t.includes("строение атома") || t.includes("электрон")) return "periodic";
  if (t.includes("металл") || t.includes("коррози")) return "metals";
  if (t.includes("алкан") || t.includes("метан") || t.includes("углеводород")) return "alkanes";
  if (t.includes("алкен") || t.includes("этен") || t.includes("этилен")) return "alkenes";
  if (t.includes("спирт") || t.includes("этанол") || t.includes("глицерин")) return "alcohols";
  if (t.includes("кислот") && (t.includes("уксус") || t.includes("карбонов"))) return "acids";
  if (t.includes("бел") || t.includes("аминокисл") || t.includes("амин")) return "proteins";
  if (t.includes("глюкоз") || t.includes("углевод")) return "carbs";
  if (t.includes("моль") || t.includes("количеств")) return "mole";
  if (t.includes("галоген") || t.includes("хлор")) return "halogens";
  if (t.includes("серн")) return "sulfuric";
  if (t.includes("азот") || t.includes("фосфор") || t.includes("удобрен")) return "nitrogen";
  if (t.includes("бензол") || t.includes("аромат")) return "benzene";
  if (t.includes("альдегид") || t.includes("формальдегид")) return "aldehydes";
  if (t.includes("полимер") || t.includes("пластмасс")) return "polymers";
  return "generic";
}

