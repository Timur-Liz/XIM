export function generateMock(req: GenerateRequest): GeneratedMaterial {
  const k = KNOWLEDGE[detectKey(req.topic)] ?? KNOWLEDGE.generic;
  const id = `m_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 7)}`;
  return {
    id,
    grade: req.grade,
    topic: req.topic,
    difficulty: req.difficulty,
    lang: req.lang,
    createdAt: new Date().toISOString(),
    worksheet: buildWorksheet(req, k),
    plan: buildPlan(req, k),
    cheat: buildCheat(req, k),
    quiz: req.includeQuiz || req.materialType === "quiz" || req.materialType === "all" ? buildQuiz(req, k) : [],
    flashcards: buildFlashcards(k),
    crossword: req.includeCrossword ? buildCrossword(req, k) : "",
    mock: true,
  };
}

/** Serialize material into a streamable text format with section markers. */
export function serializeMaterial(m: GeneratedMaterial): string {
  const parts: string[] = [];
  parts.push(`===META===${JSON.stringify({ id: m.id, grade: m.grade, topic: m.topic, difficulty: m.difficulty, lang: m.lang, createdAt: m.createdAt, mock: m.mock })}`);
  parts.push(`===WORKSHEET===\n${m.worksheet}`);
  parts.push(`===PLAN===\n${m.plan}`);
  parts.push(`===CHEAT===\n${m.cheat}`);
  parts.push(`===QUIZ===${JSON.stringify(m.quiz)}`);
  parts.push(`===FLASHCARDS===${JSON.stringify(m.flashcards)}`);
  parts.push(`===CROSSWORD===\n${m.crossword}`);
  return parts.join("\n");
}

export function parseStreamed(text: string): Partial<GeneratedMaterial> & { meta?: Record<string, unknown> } {
  const out: Record<string, unknown> = {};
  const sections = text.split(/===(WORKSHEET|PLAN|CHEAT|QUIZ|FLASHCARDS|CROSSWORD|META)===/);
  // sections: [pre, marker, content, marker, content, ...]
  for (let i = 1; i < sections.length; i += 2) {
    const marker = sections[i];
    const content = (sections[i + 1] ?? "").trim();
    if (marker === "META") {
      try { out.meta = JSON.parse(content); } catch { /* ignore */ }
    } else if (marker === "QUIZ") {
      try { out.quiz = JSON.parse(content); } catch { out.quiz = []; }
    } else if (marker === "FLASHCARDS") {
      try { out.flashcards = JSON.parse(content); } catch { out.flashcards = []; }
    } else if (marker === "WORKSHEET") out.worksheet = content;
    else if (marker === "PLAN") out.plan = content;
    else if (marker === "CHEAT") out.cheat = content;
    else if (marker === "CROSSWORD") out.crossword = content;
  }
  return out as Partial<GeneratedMaterial> & { meta?: Record<string, unknown> };
}
