import type { GenerateRequest } from "@/types";

export function buildPrompt(req: GenerateRequest): string {
  const gradeNote: Record<number, string> = {
    7: "7 класс — «Введение в химию»: вещества, смеси, атомы, молекулы, химические уравнения, воздух, вода.",
    8: "8 класс — «Первоначальные химические понятия», «Кислород. Водород. Вода. Растворы»: кислоты, основания, соли, оксиды, моль, ОВР.",
    9: "9 класс — «Классы неорганических соединений», «Периодический закон»: строение атома, связь, металлы, неметаллы, скорость реакции.",
    10: "10 класс — «Органическая химия»: углеводороды, спирты, альдегиды, карбоновые кислоты.",
    11: "11 класс — «Органическая химия», «Химия и жизнь»: амины, белки, углеводы, полимеры, химическое производство.",
  };
  const diffNote: Record<string, string> = {
    easy: "лёгкий (базовый, с опорой на учебник)",
    medium: "средний (по образцу из учебника)",
    hard: "повышенный (самостоятельные выводы и расчёты)",
    olympiad: "олимпиадный (нестандартные задачи)",
  };
  return `Ты — опытный учитель химии из Республики Беларусь. Составь учебные материалы по теме «${req.topic}» для ${req.grade} класса.
Контекст программы РБ: ${gradeNote[req.grade]}
Сложность: ${diffNote[req.difficulty]}. Язык вывода: ${req.lang === "by" ? "белорусский" : "русский"}.

Верни ответ СТРОГО в формате с маркерами секций (без лишнего текста до/после):

===WORKSHEET===
(Рабочий лист для учеников в Markdown: 3 части — разминка, основная, рефлексия; типы заданий: тест, пропуски, соответствие, таблица, задача, творческое. С пропусками вида _______.)

===PLAN===
(План-конспект урока в Markdown: тема, цель, задачи, оборудование, этапы с таймингом — оргмомент, актуализация, изучение, закрепление, применение, рефлексия, домашнее задание; вопросы для контроля.)

===CHEAT===
(Краткий опорный конспект-шпаргалка в Markdown: определение, формулы, свойства, уравнения, «запомни».)

===QUIZ===
(JSON-массив из 7 вопросов: [{"q":"...","options":["...","...","...","..."],"answer":0,"explain":"..."}]. answer — индекс правильного варианта.)

===FLASHCARDS===
(JSON-массив карточек: [{"front":"...","back":"..."}]. 6-8 карточек.)

===CROSSWORD===
(Кроссворд в Markdown: вопросы по горизонтали/вертикали и схема сетки. Если кроссворд не нужен — оставь пустым.)

Требования: соответствие программе РБ, научная точность, дружелюбный тон, формулы в виде текста (H₂SO₄, CO₂ и т.п.), без эмодзи в избытке.`;
}
